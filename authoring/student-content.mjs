export function studentSlide(slide,topic,index,worked){
 const suffix=slide.id.slice(topic.id.length+1),qi=Number(suffix.match(/^Q0(\d)/)?.[1]||0)-1;
 if(suffix==='prerequisites')slide.bullets=[
  'WMS — система управления складом; ТСД — терминал сбора данных; ERP — система планирования ресурсов предприятия.',
  vocabulary[index],
  'Числа и правила примеров учебные. Для самостоятельного прохождения прочитайте разбор, сравните условия в эксперименте и выполните самопроверку.'
 ];
 if(qi>=0){
  const w=worked[qi],v=variants[index][qi];
  if(suffix.endsWith('-input'))slide.bullets=['Определите, какие данные подтверждены и какое решение нужно получить.','Предложите ход решения; на следующем слайде сопоставьте его со схемой и разбором.'];
  if(suffix.endsWith('-worked')){slide.body=w[1];slide.visual.caption=w[2]+' '+slide.visual.caption;}
  if(suffix.endsWith('-boundary'))Object.assign(slide,{title:'Изменённый случай: разбор',body:v.condition,bullets:[v.action,v.result,'Граница вывода: '+w[3]]});
  if(suffix.endsWith('-practice'))Object.assign(slide,{kicker:'Эксперимент перед самопроверкой',body:'Сравните исходное и изменённое условия. Проверьте решение на новых данных в этом же эксперименте.'});
  if(slide.task?.type==='multiple')slide.task.prompt='Вопрос: '+topic.concepts.slice(qi*2,qi*2+2).map(x=>x.name.toLowerCase()).join(' и ')+'. '+slide.task.prompt.replace('для текущей ситуации','по изученным правилам');
 }
 return slide;
}

